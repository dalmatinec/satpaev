_VAR = re.compile(r"\{([a-z_]+)\}")


def fill(template: str, values: dict) -> str:
    """Подставить только известные {переменные}, остальные фигурные скобки не трогать."""
    if not values:
        return template
    return _VAR.sub(lambda m: str(values[m.group(1)]) if m.group(1) in values else m.group(0), template)


_TAG = re.compile(r"<[^>]+>")


def strip_html(value: str) -> str:
    """Текст без тегов: для кнопок и всплывающих уведомлений."""
    import html as _html

    return _html.unescape(_TAG.sub("", value or ""))
